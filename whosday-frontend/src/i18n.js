import React, { createContext, useContext, useEffect, useMemo, useState } from "react";
import { NativeModules, Platform } from "react-native";
import AsyncStorage from "@react-native-async-storage/async-storage";

export const LANGUAGES = [
  { code: "fr", label: "Français" },
  { code: "de", label: "Deutsch" },
  { code: "en", label: "English" },
];
const SUPPORTED = LANGUAGES.map((l) => l.code);

// Detect the device language without a native dependency.
function detectDeviceLang() {
  try {
    const raw =
      (Platform.OS === "ios"
        ? NativeModules.SettingsManager?.settings?.AppleLocale ||
          NativeModules.SettingsManager?.settings?.AppleLanguages?.[0]
        : NativeModules.I18nManager?.localeIdentifier) ||
      (typeof Intl !== "undefined" && Intl.DateTimeFormat().resolvedOptions().locale) ||
      "en";
    const two = String(raw).toLowerCase().slice(0, 2);
    return SUPPORTED.includes(two) ? two : "en";
  } catch {
    return "en";
  }
}

// Module-level current language, so non-React code (reminders, etc.) can
// translate too. Kept in sync by the provider.
let currentLang = detectDeviceLang();

export function t(key, params) {
  const table = TR[currentLang] || TR.en;
  let str = table[key] ?? TR.en[key] ?? key;
  if (params) {
    for (const k of Object.keys(params)) str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(params[k]));
  }
  return str;
}

export function getTemplates() {
  return (TR[currentLang] || TR.en)._templates;
}

const I18nContext = createContext({ lang: currentLang, setLang: () => {}, t });

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(currentLang);

  useEffect(() => {
    AsyncStorage.getItem("appLang").then((v) => {
      if (v && SUPPORTED.includes(v)) {
        currentLang = v;
        setLangState(v);
      }
    });
  }, []);

  const setLang = async (l) => {
    currentLang = l;
    setLangState(l);
    await AsyncStorage.setItem("appLang", l).catch(() => {});
  };

  // Re-created when lang changes so consumers re-render.
  const value = useMemo(() => ({ lang, setLang, t: (k, p) => t(k, p) }), [lang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

